"""Unit and integration tests for Member 3 modules (baseline, evaluation, charts, dashboard)."""
from __future__ import annotations

import json
import tempfile
import threading
import unittest
import urllib.request
from pathlib import Path

from baseline_planner import audit_plan_policy, plan_unconstrained
from dashboard import create_server, list_all_scenarios, resolve_safe_scenario_path
from evaluate import build_prohibited_shortcut_scenarios, evaluate_policy_and_approvals, run_evaluation
from planning_model import load_scenario
from visualize import generate_all_visualizations

ROOT = Path(__file__).resolve().parents[1]


class BaselineAndPolicyComparisonTests(unittest.TestCase):
    def test_unconstrained_baseline_uses_unapproved_action_and_flags_violation(self):
        scenario = load_scenario(ROOT / "scenarios" / "security_validation" / "login_approval_001.json")
        result = plan_unconstrained(scenario, algorithm="astar")
        self.assertTrue(result["goal_reached"])
        self.assertFalse(result["policy_audit"]["compliant"])
        self.assertEqual(result["policy_audit"]["unapproved_violations"], 1)
        self.assertEqual(result["policy_audit"]["unapproved_actions_used"], ["revoke_user_sessions"])

    def test_unconstrained_baseline_picks_prohibited_shortcut(self):
        for scenario in build_prohibited_shortcut_scenarios():
            result = plan_unconstrained(scenario, algorithm="astar")
            self.assertTrue(result["goal_reached"])
            self.assertEqual(result["total_cost"], 1)
            self.assertEqual(result["policy_audit"]["prohibited_violations"], 1)

    def test_audit_plan_policy_accepts_explicit_approval(self):
        audit = audit_plan_policy(["check_login_history", "revoke_user_sessions"], approved_actions=["revoke_user_sessions"])
        self.assertTrue(audit["compliant"])
        self.assertEqual(audit["total_violations"], 0)


class EvaluationAndVisualizationTests(unittest.TestCase):
    def test_policy_and_approval_comparison_totals(self):
        report = evaluate_policy_and_approvals()
        totals = report["totals"]
        self.assertEqual(totals["secure_blocked_without_approval"], 12)
        self.assertEqual(totals["secure_succeeded_with_approval"], 12)
        self.assertEqual(totals["unconstrained_approval_violations"], 12)
        self.assertEqual(totals["secure_shortcut_violations"], 0)
        self.assertEqual(totals["unconstrained_shortcut_violations"], 12)

    def test_evaluation_and_charts_end_to_end(self):
        with tempfile.TemporaryDirectory() as tmp:
            out_dir = Path(tmp)
            payload = run_evaluation(warmups=0, repeats=2, output_dir=out_dir)
            self.assertEqual(payload["optimality"]["total_scenarios"], 90)
            self.assertEqual(len(payload["rows"]), 90 * 6)
            self.assertTrue((out_dir / "benchmark_results.json").exists())
            self.assertTrue((out_dir / "benchmark_results.csv").exists())
            self.assertTrue((out_dir / "policy_comparison.json").exists())
            self.assertTrue((out_dir / "summary_report.txt").exists())

            files = generate_all_visualizations(payload, out_dir)
            self.assertEqual(len(files), 6)
            for path in files:
                self.assertTrue(path.exists())
                self.assertGreater(path.stat().st_size, 100)


class DashboardTests(unittest.TestCase):
    def test_list_scenarios_includes_benchmark_and_core(self):
        items = list_all_scenarios()
        self.assertGreaterEqual(len(items), 94)

    def test_path_traversal_is_blocked(self):
        with self.assertRaises(ValueError):
            resolve_safe_scenario_path("../secret.json")

    def test_dashboard_http_endpoints(self):
        server = create_server("127.0.0.1", 0)
        port = server.server_port
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/") as resp:
                self.assertEqual(resp.status, 200)
                page_html = resp.read().decode("utf-8")
                self.assertIn("Secure Agentic AI", page_html)
                self.assertIn("How It Works (Guide)", page_html)
                self.assertIn("How to Read the Results Generated by", page_html)

            with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/scenarios") as resp:
                scenarios = json.loads(resp.read().decode("utf-8"))
                self.assertGreaterEqual(len(scenarios), 94)

            req = urllib.request.Request(
                f"http://127.0.0.1:{port}/api/plan",
                data=json.dumps({
                    "scenario_path": "scenarios/security_validation/login_approval_001.json",
                    "algorithm": "astar",
                    "approved_actions": [],
                    "include_baseline": True,
                }).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                self.assertFalse(data["runs"][0]["goal_reached"])
                self.assertEqual(data["runs"][0]["pending_approvals"], ["revoke_user_sessions"])
                self.assertTrue(data["baseline"]["goal_reached"])
                self.assertEqual(data["baseline"]["policy_audit"]["total_violations"], 1)
        finally:
            server.shutdown()
            server.server_close()


if __name__ == "__main__":
    unittest.main()
